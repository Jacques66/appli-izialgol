using Studio.Ide.Services;

namespace Studio.Ide.Browser;

/// <summary>Platform services of the browser: no external process (no external console, no executable
/// generation), files in the virtual file system of <see cref="VirtualFiles"/>.</summary>
sealed class BrowserPlatform : IPlatformServices
{
    public string ExternalConsoleName => "console";
    public bool SupportsExternalConsole => false;
    public bool SupportsExecutables => false;
    public string ExecutableExtension => "";
    public string ExecutableDescription => "Executable";
    public string? FindRunner() => null;
    public string RevealInFileManagerText => "Show in the file manager";
    public bool IsVirtualFileSystem => true;
    public string? ImportDirectory => VirtualFiles.Programs;

    public void WriteExecutable(string runnerPath, string targetPath, string languageId, byte[] payload) =>
        throw new PlatformNotSupportedException("Standalone executables are generated by the desktop version of AlgolStudio.");

    public ExternalRun StartInExternalConsole(string executablePath, string workingDirectory, string title) =>
        throw new PlatformNotSupportedException("There is no external console in the browser.");

    public void OpenUrl(string url) => Interop.OpenUrl(url);

    public void RevealInFileManager(string path) { }
}
